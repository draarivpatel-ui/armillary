/**
 * First-run event contract. The Rust side lives in app/src-tauri/src/firstrun.rs and serialises
 * the same shapes with serde `rename_all = "camelCase"`. The app re-exports these from
 * app/src/firstrun/events.ts and wires them to Tauri's `listen`.
 *
 * Order on the wire after the user presses Continue (firstrun_scan):
 *   firstrun:catalogue (once) -> firstrun:agent (once per registry entry, as detection resolves)
 *   -> firstrun:import (per found agent with a history adapter: started, progress..., finished | error)
 *   -> firstrun:done (once, constellations from the archive after import)
 * Nothing is emitted, detected or read before consent.
 */

export const FIRSTRUN_EVENT = {
  catalogue: "firstrun:catalogue",
  agent: "firstrun:agent",
  import: "firstrun:import",
  done: "firstrun:done",
} as const;

export type FirstRunEventName = (typeof FIRSTRUN_EVENT)[keyof typeof FIRSTRUN_EVENT];

/** Normalised family keys, identical to app/src-tauri/src/agents.rs normalize_family. */
export type FamilyKey =
  | "anthropic"
  | "openai"
  | "google"
  | "github-microsoft"
  | "cursor"
  | "open-source-clis"
  | "chinese-labs"
  | "other";

export const FAMILY_KEYS: readonly FamilyKey[] = [
  "anthropic",
  "openai",
  "google",
  "github-microsoft",
  "cursor",
  "open-source-clis",
  "chinese-labs",
  "other",
];

export interface CatalogueEntry {
  id: string;
  name: string;
  vendor: string;
  family: FamilyKey;
  /** Raw registry kind: cli, desktop, ide, cloud, extension, ide_extension, server, tui, terminal. */
  kind: string;
  /** True when the registry has a history adapter for it (it can be imported, not only detected). */
  history: boolean;
  /**
   * The folders this agent's data lives in on this OS, from the registry (home shown as "~",
   * environment overrides such as $CODEX_HOME kept as written, project-relative patterns omitted).
   * Present in firstrun_plan; may be empty in firstrun:catalogue.
   */
  folders: string[];
}

/** firstrun_plan(): registry only, no filesystem access. Shown on the consent plaque. */
export interface FirstRunPlan {
  platform: "macos" | "linux" | "windows";
  entries: CatalogueEntry[];
  /** Every folder pattern the registry will look in on this OS, home shown as "~", sorted, deduplicated. */
  folders: string[];
}

export interface CataloguePayload {
  platform: "macos" | "linux" | "windows";
  entries: CatalogueEntry[];
}

export interface AgentPayload {
  id: string;
  found: boolean;
  /** Passive detection never runs binaries, so this is usually null. */
  version: string | null;
  /** Existing data folders, home shown as "~". */
  folders: string[];
  history: boolean;
}

export type ImportPhase = "started" | "progress" | "finished" | "error";

export interface ImportPayload {
  agentId: string;
  phase: ImportPhase;
  /** Sessions accepted into the archive so far for this agent. */
  sessionsImported: number;
  /** Sessions discovered so far for this agent (grows while sources are listed). */
  sessionsKnown: number;
  /** Reason, for phase "error" (and for a finished run that had source read errors). */
  error: string | null;
  /** Project folder basenames seen in this agent's imported sessions (phase "finished"). */
  projects: string[];
}

export interface ConstellationMember {
  agentId: string;
  /** This agent's sessions in this project. */
  sessions: number;
}

export interface Constellation {
  /** Project folder basename. */
  name: string;
  /** Full project root as recorded in the archive (used to match the Orrery's suns). */
  root: string;
  /** Agent ids, sorted. */
  agents: string[];
  sessions: number;
  /** Per-agent weight in this project, sorted by sessions (desc) then agent id. */
  members: ConstellationMember[];
}

export interface DonePayload {
  constellations: Constellation[];
  liveSessions: number;
  sessionsImported: number;
  agentsFound: number;
  catalogueSize: number;
  errors: number;
}

export type CoreEvent =
  | { name: typeof FIRSTRUN_EVENT.catalogue; payload: CataloguePayload }
  | { name: typeof FIRSTRUN_EVENT.agent; payload: AgentPayload }
  | { name: typeof FIRSTRUN_EVENT.import; payload: ImportPayload }
  | { name: typeof FIRSTRUN_EVENT.done; payload: DonePayload };

/** A recorded or scripted log entry: `at` is ms after consent (the scan start). */
export interface RecordedEvent {
  at: number;
  name: FirstRunEventName;
  payload: unknown;
}

export interface RecordedLog {
  /** Human note on provenance, e.g. "mock: generated by firstrun.rs over demo/dataset". */
  source: string;
  plan: FirstRunPlan;
  events: RecordedEvent[];
}

/** firstrun_status(): persisted in <app_data_dir>/firstrun.json (browser: localStorage). */
export interface FirstRunStatus {
  consented: boolean;
  completed: boolean;
}

// ---------------------------------------------------------------------------------------------
// Parsing: payloads cross a process boundary, so validate shape before they reach the scene.

const isObj = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null;
const isStr = (v: unknown): v is string => typeof v === "string";
const isNum = (v: unknown): v is number => typeof v === "number" && Number.isFinite(v);
const isStrArr = (v: unknown): v is string[] => Array.isArray(v) && v.every(isStr);

export function normaliseFamily(v: unknown): FamilyKey {
  return (FAMILY_KEYS as readonly string[]).includes(v as string) ? (v as FamilyKey) : "other";
}

function parseEntry(v: unknown): CatalogueEntry | null {
  if (!isObj(v) || !isStr(v.id) || !isStr(v.name)) return null;
  return {
    id: v.id,
    name: v.name,
    vendor: isStr(v.vendor) ? v.vendor : "",
    family: normaliseFamily(v.family),
    kind: isStr(v.kind) ? v.kind : "cli",
    history: v.history === true,
    folders: isStrArr(v.folders) ? v.folders : [],
  };
}

function parsePlatform(v: unknown): FirstRunPlan["platform"] {
  return v === "linux" || v === "windows" ? v : "macos";
}

export function parsePlan(v: unknown): FirstRunPlan | null {
  if (!isObj(v) || !Array.isArray(v.entries)) return null;
  const entries = v.entries.map(parseEntry).filter((e): e is CatalogueEntry => e !== null);
  return { platform: parsePlatform(v.platform), entries, folders: isStrArr(v.folders) ? v.folders : [] };
}

export function parseCoreEvent(name: string, payload: unknown): CoreEvent | null {
  if (!isObj(payload)) return null;
  switch (name) {
    case FIRSTRUN_EVENT.catalogue: {
      if (!Array.isArray(payload.entries)) return null;
      const entries = payload.entries.map(parseEntry).filter((e): e is CatalogueEntry => e !== null);
      return { name, payload: { platform: parsePlatform(payload.platform), entries } };
    }
    case FIRSTRUN_EVENT.agent: {
      if (!isStr(payload.id) || typeof payload.found !== "boolean") return null;
      return {
        name,
        payload: {
          id: payload.id,
          found: payload.found,
          version: isStr(payload.version) ? payload.version : null,
          folders: isStrArr(payload.folders) ? payload.folders : [],
          history: payload.history === true,
        },
      };
    }
    case FIRSTRUN_EVENT.import: {
      const phase = payload.phase;
      if (!isStr(payload.agentId) || !(phase === "started" || phase === "progress" || phase === "finished" || phase === "error")) {
        return null;
      }
      return {
        name,
        payload: {
          agentId: payload.agentId,
          phase,
          sessionsImported: isNum(payload.sessionsImported) ? Math.max(0, payload.sessionsImported) : 0,
          sessionsKnown: isNum(payload.sessionsKnown) ? Math.max(0, payload.sessionsKnown) : 0,
          error: isStr(payload.error) ? payload.error : null,
          projects: isStrArr(payload.projects) ? payload.projects : [],
        },
      };
    }
    case FIRSTRUN_EVENT.done: {
      if (!Array.isArray(payload.constellations)) return null;
      const constellations: Constellation[] = [];
      for (const c of payload.constellations) {
        if (!isObj(c) || !isStr(c.name) || !isStrArr(c.agents)) continue;
        const members: ConstellationMember[] = [];
        if (Array.isArray(c.members)) {
          for (const m of c.members) {
            if (isObj(m) && isStr(m.agentId) && isNum(m.sessions)) members.push({ agentId: m.agentId, sessions: m.sessions });
          }
        }
        if (members.length === 0) for (const a of c.agents) members.push({ agentId: a, sessions: 0 });
        constellations.push({
          name: c.name,
          root: isStr(c.root) ? c.root : c.name,
          agents: c.agents,
          sessions: isNum(c.sessions) ? c.sessions : 0,
          members,
        });
      }
      const n = (k: string) => (isNum(payload[k]) ? (payload[k] as number) : 0);
      return {
        name,
        payload: {
          constellations,
          liveSessions: n("liveSessions"),
          sessionsImported: n("sessionsImported"),
          agentsFound: n("agentsFound"),
          catalogueSize: n("catalogueSize"),
          errors: n("errors"),
        },
      };
    }
    default:
      return null;
  }
}

export function parseRecordedLog(v: unknown): RecordedLog | null {
  if (!isObj(v) || !Array.isArray(v.events)) return null;
  const plan = parsePlan(v.plan);
  if (!plan) return null;
  const events: RecordedEvent[] = [];
  for (const e of v.events) {
    if (!isObj(e) || !isNum(e.at) || !isStr(e.name)) continue;
    if (!parseCoreEvent(e.name, e.payload)) continue;
    events.push({ at: e.at, name: e.name as FirstRunEventName, payload: e.payload });
  }
  events.sort((a, b) => a.at - b.at);
  return { source: isStr(v.source) ? v.source : "unknown", plan, events };
}
